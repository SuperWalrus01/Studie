/**
 * Regenerates docs/ROUTES.md from the bundled GTFS subset plus the app config.
 * Run after `npm run bundle-gtfs` so the doc matches the shipped timetable.
 *
 *   npx tsx --env-file=.env.local scripts/generate-route-stats.mjs
 */
import { writeFileSync, readFileSync } from "fs";
import { ROUTE_COLORS } from "../lib/routeColors.ts";
import { getStopLabel } from "../lib/stopLabels.ts";
import { CITY_CONNECTOR_ROUTES, ROUTE_NAMES } from "../lib/stops.ts";
import { VOICE_PLACES } from "../lib/voice.ts";

const subset = JSON.parse(readFileSync("data/gtfs-subset.json", "utf8"));

/** Mirrors ROUTE_AGENCY in lib/gtfs.ts — GTFS agency_id per route */
const AGENCY = { "87": "OP17" };
const agencyOf = (r) => AGENCY[r] ?? "OP4";

const OPERATOR = { OP4: "National Express Coventry", OP17: "Stagecoach" };

/** GTFS encodes after-midnight departures as 24:00+ — keep them unwrapped */
const hhmm = (sec) =>
  `${String(Math.floor(sec / 3600)).padStart(2, "0")}:${String(
    Math.floor((sec % 3600) / 60)
  ).padStart(2, "0")}`;

/** route → aggregated stats */
const stats = new Map();
for (const e of subset.edges) {
  let r = stats.get(e.routeShortName);
  if (!r) {
    r = {
      route: e.routeShortName,
      edges: 0,
      trips: new Set(),
      services: new Set(),
      origins: new Map(),
      dests: new Set(),
      first: Infinity,
      last: -Infinity,
    };
    stats.set(e.routeShortName, r);
  }
  r.edges++;
  r.trips.add(e.tripId);
  r.services.add(e.serviceId);
  r.dests.add(getStopLabel(e.destStopId));
  const originLabel = getStopLabel(e.originStopId);
  r.origins.set(originLabel, (r.origins.get(originLabel) ?? 0) + 1);
  r.first = Math.min(r.first, e.departureSec);
  r.last = Math.max(r.last, e.departureSec);
}

const ordered = [...ROUTE_NAMES, ...CITY_CONNECTOR_ROUTES].filter((r) =>
  stats.has(r)
);
const missing = [...ROUTE_NAMES, ...CITY_CONNECTOR_ROUTES].filter(
  (r) => !stats.has(r)
);

const totalTrips = ordered.reduce((n, r) => n + stats.get(r).trips.size, 0);

const L = [];
L.push("# Routes and stats tracked by the app");
L.push("");
L.push(
  "Generated by `scripts/generate-route-stats.mjs` from `data/gtfs-subset.json`."
);
L.push("Do not edit by hand — rerun the script after `npm run bundle-gtfs`.");
L.push("");
L.push(`- **Timetable bundle built:** ${subset.builtAt}`);
L.push(`- **Routes tracked:** ${ordered.length}`);
L.push(`- **Distinct trips:** ${totalTrips.toLocaleString("en-GB")}`);
L.push(
  `- **Stop-to-stop edges:** ${subset.edges.length.toLocaleString("en-GB")}`
);
L.push(`- **Named places the Alexa skill accepts:** ${VOICE_PLACES.length}`);
if (missing.length) {
  L.push(
    `- **Configured but absent from this bundle:** ${missing.join(", ")}`
  );
}
L.push("");
L.push(
  "> The bundle is a *subset*: it only holds edges between the stops in " +
    "`lib/stops.constants.mjs`. Trip counts are edges along this corridor, not " +
    "the operator's full network."
);
L.push("");
L.push(
  "> First/last times are GTFS service-day clock times, so a value like `25:22` " +
    "means 01:22 the following morning."
);
L.push("");

L.push("## Per-route summary");
L.push("");
L.push(
  "| Route | Role | Operator | Trips | Services | Origins tracked | First | Last | Badge |"
);
L.push("|---|---|---|---:|---:|---:|---|---|---|");
for (const r of ordered) {
  const s = stats.get(r);
  const role = ROUTE_NAMES.includes(r) ? "Campus corridor" : "City connector";
  L.push(
    `| **${r}** | ${role} | ${OPERATOR[agencyOf(r)]} (${agencyOf(r)}) | ${
      s.trips.size
    } | ${s.services.size} | ${s.origins.size} | ${hhmm(s.first)} | ${hhmm(
      s.last
    )} | \`${ROUTE_COLORS[r] ?? "—"}\` |`
  );
}
L.push("");

L.push("## What is tracked per route");
L.push("");
L.push("| Field | Source | Used by |");
L.push("|---|---|---|");
[
  ["`routeShortName`", "GTFS `routes.txt`", "everything — the key for all lookups"],
  ["`tripId`", "GTFS `trips.txt`", "joins a scheduled trip to its live delay"],
  ["`serviceId`", "GTFS `calendar.txt`", "does this trip run today"],
  ["`departureSec` / `arrivalSec`", "GTFS `stop_times.txt`", "departure boards, journey duration"],
  ["`originStopId` / `destStopId`", "GTFS `stop_times.txt`", "which stop, which direction"],
  ["Live delay (seconds)", "GTFS-RT `trip_updates`", "`leaveInMinutes`, \"running late\" answers"],
  ["Badge colour", "`lib/routeColors.ts`", "map markers and route badges"],
  ["Agency", "`lib/gtfs.ts` `ROUTE_AGENCY`", "disambiguates duplicate short names"],
  ["Walk minutes to stop", "`lib/journeys.ts`", "door-to-door comparison"],
].forEach(([f, src, use]) => L.push(`| ${f} | ${src} | ${use} |`));
L.push("");

L.push("## Where each route runs");
L.push("");
for (const r of ordered) {
  const s = stats.get(r);
  L.push(`### ${r}`);
  L.push("");
  L.push(
    `${s.trips.size} trips · ${s.edges} edges · serves ${s.origins.size} boarding point${
      s.origins.size === 1 ? "" : "s"
    } · runs ${hhmm(s.first)}–${hhmm(s.last)}`
  );
  L.push("");
  L.push("| Boards at | Edges | Reaches |");
  L.push("|---|---:|---|");
  const originsSorted = [...s.origins].sort((a, b) => b[1] - a[1]);
  for (const [label, count] of originsSorted) {
    const reaches = new Set();
    for (const e of subset.edges) {
      if (e.routeShortName !== r) continue;
      if (getStopLabel(e.originStopId) !== label) continue;
      reaches.add(getStopLabel(e.destStopId));
    }
    L.push(`| ${label} | ${count} | ${[...reaches].sort().join(", ")} |`);
  }
  L.push("");
}

L.push("## Places the Alexa skill understands");
L.push("");
L.push("| Spoken as | Slot id | NaPTAN bays | Routes seen here |");
L.push("|---|---|---:|---|");
for (const place of VOICE_PLACES) {
  const ids = new Set(place.stopIds);
  const routes = new Set();
  for (const e of subset.edges) {
    if (ids.has(e.originStopId)) routes.add(e.routeShortName);
  }
  const sorted = [...routes].sort(
    (a, b) => ordered.indexOf(a) - ordered.indexOf(b)
  );
  L.push(
    `| ${place.label} | \`${place.slug}\` | ${place.stopIds.length} | ${
      sorted.join(", ") || "—"
    } |`
  );
}
L.push("");
L.push(
  "Each place also accepts spoken synonyms — see `VOICE_PLACES` in `lib/voice.ts`."
);
L.push("");

writeFileSync("docs/ROUTES.md", L.join("\n"));
console.log(
  `docs/ROUTES.md written — ${ordered.length} routes, ${totalTrips} trips.`
);
